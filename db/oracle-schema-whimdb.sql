CREATE TABLE users (
  id VARCHAR2(36) PRIMARY KEY,
  name VARCHAR2(255) NOT NULL,
  email VARCHAR2(320) NOT NULL UNIQUE,
  password_hash VARCHAR2(255),
  is_active NUMBER(1) DEFAULT 1 NOT NULL
    CHECK (is_active IN (0, 1)),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE customers (
  id VARCHAR2(36) PRIMARY KEY,
  whim_id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY
    (START WITH 10000 INCREMENT BY 1),
  name VARCHAR2(255) NOT NULL,
  email VARCHAR2(320) UNIQUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT customers_whim_id_uq UNIQUE (whim_id)
);

CREATE TABLE audit_log (
  id VARCHAR2(36) PRIMARY KEY,
  action VARCHAR2(255) NOT NULL,
  user_id VARCHAR2(36),
  customer_id VARCHAR2(36),
  transaction_id VARCHAR2(36),
  details CLOB CHECK (details IS JSON),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT audit_user_fk FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT audit_customer_fk FOREIGN KEY (customer_id)
    REFERENCES customers(id)
);

CREATE TABLE user_sessions (
  sid VARCHAR2(255) PRIMARY KEY,
  sess CLOB NOT NULL CHECK (sess IS JSON),
  expire TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX user_sessions_expire_idx ON user_sessions(expire);

CREATE OR REPLACE TRIGGER audit_log_immutable
BEFORE UPDATE OR DELETE ON audit_log
BEGIN
  RAISE_APPLICATION_ERROR(-20001, 'Audit log records are immutable');
END;

